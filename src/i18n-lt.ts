/** Lithuanian has three plural forms: 1, 21, 31… (not 11); 2–9, 22–29… (not 12–19); and 0, 10–20, 30… */
export const ltPlural = (n: number, one: string, few: string, many: string) => {
  const d = n % 10;
  const t = n % 100;
  if (d === 1 && t !== 11) return one;
  if (d >= 2 && d <= 9 && (t < 12 || t > 19)) return few;
  return many;
};

